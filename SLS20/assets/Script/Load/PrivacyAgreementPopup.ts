export default class PrivacyAgreementPopup {
    private static readonly POPUP_NAME = 'PrivacyAgreementPopup';

    static showUserAgreement(parent: cc.Node): cc.Node {
        return this.show(parent, USER_AGREEMENT_TITLE, USER_AGREEMENT);
    }

    static showPrivacyGuide(parent: cc.Node): cc.Node {
        return this.show(parent, PRIVACY_GUIDE_TITLE, PRIVACY_GUIDE);
    }

    private static show(parent: cc.Node, title: string, agreement: string): cc.Node {
        const existing = parent.getChildByName(this.POPUP_NAME);
        if (existing && cc.isValid(existing)) {
            existing.active = true;
            this.updateContent(existing, title, agreement);
            return existing;
        }

        return this.create(parent, title, agreement);
    }

    private static create(parent: cc.Node, title: string, agreement: string): cc.Node {
        const root = new cc.Node(this.POPUP_NAME);
        root.setContentSize(720, 1280);
        root.setPosition(0, 0);
        root.zIndex = 10000;
        parent.addChild(root);

        const mask = new cc.Node('Mask');
        mask.setContentSize(2000, 2000);
        root.addChild(mask);
        const maskGraphics = mask.addComponent(cc.Graphics);
        maskGraphics.fillColor = cc.color(0, 0, 0, 190);
        maskGraphics.fillRect(-1000, -1000, 2000, 2000);
        mask.on(cc.Node.EventType.TOUCH_START, () => undefined);
        mask.on(cc.Node.EventType.TOUCH_END, () => root.active = false);

        const panel = new cc.Node('Panel');
        panel.setContentSize(640, 1000);
        root.addChild(panel);
        panel.addComponent(cc.BlockInputEvents);
        const panelGraphics = panel.addComponent(cc.Graphics);
        panelGraphics.fillColor = cc.color(255, 247, 222, 255);
        panelGraphics.strokeColor = cc.color(143, 59, 36, 255);
        panelGraphics.lineWidth = 4;
        panelGraphics.roundRect(-320, -500, 640, 1000, 8);
        panelGraphics.fill();
        panelGraphics.stroke();

        this.createLabel(
            panel,
            'Title',
            title,
            cc.v2(0, 440),
            cc.size(480, 54),
            30,
            38,
            cc.color(143, 59, 36, 255),
            cc.Label.HorizontalAlign.CENTER
        );

        const divider = new cc.Node('Divider');
        divider.setPosition(0, 395);
        panel.addChild(divider);
        const dividerGraphics = divider.addComponent(cc.Graphics);
        dividerGraphics.strokeColor = cc.color(210, 171, 113, 255);
        dividerGraphics.lineWidth = 2;
        dividerGraphics.moveTo(-275, 0);
        dividerGraphics.lineTo(275, 0);
        dividerGraphics.stroke();

        const closeButton = new cc.Node('CloseButton');
        closeButton.setContentSize(72, 72);
        closeButton.setPosition(275, 445);
        panel.addChild(closeButton);
        const closeGraphics = closeButton.addComponent(cc.Graphics);
        closeGraphics.strokeColor = cc.color(143, 59, 36, 255);
        closeGraphics.lineWidth = 6;
        closeGraphics.lineCap = cc.Graphics.LineCap.ROUND;
        closeGraphics.moveTo(-13, 13);
        closeGraphics.lineTo(13, -13);
        closeGraphics.moveTo(13, 13);
        closeGraphics.lineTo(-13, -13);
        closeGraphics.stroke();
        closeButton.on(cc.Node.EventType.TOUCH_END, () => root.active = false);

        const frame = new cc.Node('TextFrame');
        frame.setPosition(0, 25);
        panel.addChild(frame);
        const frameGraphics = frame.addComponent(cc.Graphics);
        frameGraphics.fillColor = cc.color(255, 252, 241, 255);
        frameGraphics.strokeColor = cc.color(226, 198, 151, 255);
        frameGraphics.lineWidth = 2;
        frameGraphics.roundRect(-285, -350, 570, 700, 6);
        frameGraphics.fill();
        frameGraphics.stroke();

        const scrollNode = new cc.Node('AgreementScrollView');
        scrollNode.setContentSize(550, 670);
        scrollNode.setPosition(0, 25);
        panel.addChild(scrollNode);
        const scrollView = scrollNode.addComponent(cc.ScrollView);
        scrollView.horizontal = false;
        scrollView.vertical = true;
        scrollView.inertia = true;
        scrollView.brake = 0.75;
        scrollView.elastic = false;
        scrollView.bounceDuration = 0.2;

        const view = new cc.Node('view');
        view.setContentSize(550, 670);
        scrollNode.addChild(view);
        view.addComponent(cc.Mask).type = cc.Mask.Type.RECT;

        const content = new cc.Node('content');
        content.setAnchorPoint(0.5, 1);
        content.setContentSize(520, 670);
        content.setPosition(0, 335);
        view.addChild(content);
        const contentLayout = content.addComponent(cc.Layout);
        contentLayout.type = cc.Layout.Type.VERTICAL;
        contentLayout.resizeMode = cc.Layout.ResizeMode.CONTAINER;
        contentLayout.verticalDirection = cc.Layout.VerticalDirection.TOP_TO_BOTTOM;
        contentLayout.paddingTop = 10;
        contentLayout.paddingBottom = 20;
        scrollView.content = content;
        this.updateAgreementBody(content, scrollView, agreement);

        const confirmButton = new cc.Node('ConfirmButton');
        confirmButton.setContentSize(240, 72);
        confirmButton.setPosition(0, -420);
        panel.addChild(confirmButton);
        const confirmGraphics = confirmButton.addComponent(cc.Graphics);
        confirmGraphics.fillColor = cc.color(157, 69, 43, 255);
        confirmGraphics.strokeColor = cc.color(113, 43, 29, 255);
        confirmGraphics.lineWidth = 3;
        confirmGraphics.roundRect(-120, -36, 240, 72, 8);
        confirmGraphics.fill();
        confirmGraphics.stroke();
        this.createLabel(
            confirmButton,
            'ConfirmLabel',
            '确认',
            cc.v2(0, 0),
            cc.size(180, 50),
            28,
            36,
            cc.color(255, 240, 194, 255),
            cc.Label.HorizontalAlign.CENTER
        );
        confirmButton.on(cc.Node.EventType.TOUCH_END, () => root.active = false);

        return root;
    }

    private static updateContent(root: cc.Node, title: string, agreement: string) {
        const panel = root.getChildByName('Panel');
        const titleNode = panel && panel.getChildByName('Title');
        const titleLabel = titleNode && titleNode.getComponent(cc.Label);
        const scrollNode = panel && panel.getChildByName('AgreementScrollView');
        const scrollView = scrollNode && scrollNode.getComponent(cc.ScrollView);
        const content = scrollView && scrollView.content;

        if (titleLabel) {
            titleLabel.string = title;
        }
        if (content && scrollView) {
            this.updateAgreementBody(content, scrollView, agreement);
        }
    }

    private static updateAgreementBody(
        content: cc.Node,
        scrollView: cc.ScrollView,
        agreement: string
    ) {
        scrollView.stopAutoScroll();
        content.setPosition(0, 335);
        content.removeAllChildren();

        agreement.replace(/\r\n/g, '\n').split('\n').forEach((paragraph, index) => {
            if (!paragraph) {
                const spacer = new cc.Node(`AgreementSpacer_${index}`);
                spacer.setContentSize(500, 17);
                content.addChild(spacer);
                return;
            }

            const paragraphNode = new cc.Node(`AgreementParagraph_${index}`);
            paragraphNode.setAnchorPoint(0.5, 1);
            paragraphNode.color = cc.color(91, 62, 46, 255);
            content.addChild(paragraphNode);

            const paragraphLabel = paragraphNode.addComponent(cc.Label);
            paragraphLabel.overflow = cc.Label.Overflow.RESIZE_HEIGHT;
            paragraphNode.setContentSize(500, 34);
            paragraphLabel.fontSize = 22;
            paragraphLabel.lineHeight = 34;
            paragraphLabel.enableWrapText = true;
            paragraphLabel.horizontalAlign = cc.Label.HorizontalAlign.LEFT;
            paragraphLabel.verticalAlign = cc.Label.VerticalAlign.TOP;
            paragraphLabel.string = paragraph;
        });

        const layout = content.getComponent(cc.Layout);
        if (layout) {
            layout.updateLayout();
        }
    }

    private static createLabel(
        parent: cc.Node,
        name: string,
        text: string,
        position: cc.Vec2,
        size: cc.Size,
        fontSize: number,
        lineHeight: number,
        color: cc.Color,
        horizontalAlign: cc.Label.HorizontalAlign
    ): cc.Label {
        const node = new cc.Node(name);
        node.setPosition(position);
        node.color = color;
        parent.addChild(node);

        const label = node.addComponent(cc.Label);
        label.overflow = cc.Label.Overflow.SHRINK;
        node.setContentSize(size);
        label.fontSize = fontSize;
        label.lineHeight = lineHeight;
        label.horizontalAlign = horizontalAlign;
        label.verticalAlign = cc.Label.VerticalAlign.CENTER;
        label.enableWrapText = true;
        label.string = text;
        return label;
    }
}
